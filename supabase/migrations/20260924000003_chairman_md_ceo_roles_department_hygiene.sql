--    function gates, so there is no second authorization system).
-- 3) Executive TITLES are not departments. `public.is_role_like_department()`
--    and `public.department_label()` are the server-side source of truth; the
--    department option lists in get_dashboard_filter_options() and
--    get_director_executive_snapshot() no longer offer "MD/CEO", and stored
