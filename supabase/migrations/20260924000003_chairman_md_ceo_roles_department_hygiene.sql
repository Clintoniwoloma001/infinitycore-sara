-- ---------------------------------------------------------------------------
-- 6. Master data hygiene: a departments row named after an executive title is
--    deactivated so it stops being offered as a department anywhere. No row is
--    deleted and no employee is reassigned — HR assigns the real department.
-- ---------------------------------------------------------------------------
do $$
declare
  v_row record;
begin
  for v_row in
    select id, name from public.departments
    where coalesce(is_active, true) and public.is_role_like_department(name)
  loop
    update public.departments set is_active = false where id = v_row.id;
    insert into public.audit_logs (action, entity_type, entity_id, user_name, details, severity)
    values ('DEPARTMENT_TITLE_DEACTIVATED','Department',v_row.id::text,'system',
      format('%s is an executive title (a role), not a department — deactivated as a department option', v_row.name),'warning');
  end loop;
end $$;

commit;
